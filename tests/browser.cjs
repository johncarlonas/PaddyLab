const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({headless: true, channel: 'msedge'});
  const page = await browser.newPage({viewport: {width: 1440, height: 1080}});
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:5000');
  await page.locator('#model-status.ready').waitFor({timeout: 120000});
  assert.equal(await page.locator('h1').innerText(), 'Rice Leaf Analysis');
  assert.equal(await page.getByRole('link', {name: 'About', exact: true}).count(), 1);
  assert.equal(await page.title(), 'PaddyLab - Rice Disease Analyzer');
  assert.equal(await page.locator('.analyzer-heading h2').innerText(), 'Leaf Analyzer');
  assert.equal(await page.locator('.choose-photo').innerText(), 'Choose a Photo');
  assert.equal(await page.locator('#analyze').innerText(), 'Analyze Photo');
  assert.equal(await page.locator('.analyzer-heading .model-status').innerText(), 'Ready to analyze');
  assert.equal(await page.locator('.analyzer-footer .model-note').innerText(), 'A prediction is a model estimate. It does not confirm disease.');
  assert.equal(await page.locator('.result-empty [data-sample]').textContent(), 'Try a sample ↗');
  assert.equal(await page.locator('.class-list').count(), 0);
  assert.equal(await page.locator('.eyebrow').count(), 0);
  await page.screenshot({path: 'tests/desktop.png', fullPage: true});
  await page.locator('[data-sample="healthy"]').click();
  await page.locator('#preview').waitFor({state: 'visible'});
  await page.locator('#analyze').click();
  await page.locator('#result').waitFor({state: 'visible', timeout: 60000});
  assert.equal(await page.locator('.score').count(), 6);
  await page.getByText('All class scores', {exact: true}).click();
  const downloadPromise = page.waitForEvent('download');
  await page.locator('#download').click();
  assert.equal((await downloadPromise).suggestedFilename(), 'paddylab-reading.json');
  await page.screenshot({path: 'tests/result.png', fullPage: true});
  await page.locator('#clear').click();
  assert.equal(await page.locator('#analyze').isDisabled(), true);
  await page.setViewportSize({width: 390, height: 844});
  await page.screenshot({path: 'tests/mobile.png', fullPage: true});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  await page.getByRole('link', {name: 'About', exact: true}).click();
  await page.locator('.class-row').first().waitFor({state: 'visible'});
  assert.equal(await page.locator('.class-row').count(), 6);
  assert.ok(page.url().endsWith('/about'));
  assert.equal(await page.title(), 'About - PaddyLab');
  assert.equal(await page.locator('.sample-link').count(), 0);
  assert.equal(await page.locator('.about-detail').count(), 3);
  assert.equal(await page.locator('.about-developer a').innerText(), 'John Carlo Nas');
  assert.equal(await page.locator('.about-intro > p').first().innerText(), 'PaddyLab is my first AI model, created to explore rice leaf conditions. It was developed as my final project for the Introduction to Artificial Intelligence course.');
  assert.equal(await page.locator('.classes-heading h2').innerText(), 'The Six Classes');
  assert.equal(await page.locator('.site-footer').innerText(), '© 2026 PaddyLab. All rights reserved.');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  await page.emulateMedia({reducedMotion: 'reduce'});
  await page.goto('http://127.0.0.1:5000/?sample=bacterial_leaf_blight');
  await page.locator('#preview').waitFor({state: 'visible'});
  assert.ok((await page.locator('#filename').textContent()).includes('bacterial_leaf_blight'));
  await page.waitForTimeout(100);
  assert.equal(await page.locator('html.motion-ready').count(), 0);
  assert.deepEqual(errors, []);
  console.log('Browser checks passed: inference, scores, download, reset, mobile width, About page, class grid, sample loading, reduced motion.');
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
