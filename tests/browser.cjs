const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({headless: true, channel: 'msedge'});
  const page = await browser.newPage({viewport: {width: 1440, height: 1080}});
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:5000');
  await page.locator('#model-status.ready').waitFor({timeout: 120000});
  assert.equal(await page.locator('h1').innerText(), 'Rice Leaf Analysis');
  assert.equal(await page.getByRole('link', {name: 'About', exact: true}).count(), 1);
  assert.equal(await page.getByRole('link', {name: 'Analyze', exact: true}).count(), 0);
  assert.equal(await page.locator('.about-link').evaluate(element => getComputedStyle(element).backgroundColor), 'rgb(32, 41, 31)');
  assert.equal(await page.locator('.about-link').evaluate(element => getComputedStyle(element).color), 'rgb(255, 255, 255)');
  assert.equal(await page.title(), 'PaddyLab - Rice Disease Analyzer');
  assert.equal(await page.locator('.analyzer-heading h2').innerText(), 'Leaf Analyzer');
  assert.equal(await page.locator('.choose-photo').innerText(), 'Choose a Photo');
  assert.equal(await page.locator('#analyze').innerText(), 'Analyze Photo');
  assert.equal(await page.locator('.analyzer-heading .model-status').innerText(), 'Ready');
  assert.equal(await page.locator('.analyzer-footer .model-note').innerText(), 'A prediction is a model estimate. It does not confirm disease.');
  assert.equal(await page.locator('.result-empty [data-sample]').textContent(), 'Try a sample');
  assert.equal(await page.locator('.sample-action span').count(), 0);
  assert.equal(await page.locator('.sample-action').evaluate(element => getComputedStyle(element).borderTopWidth), '1px');
  assert.equal(await page.locator('.file-info').evaluate(element => getComputedStyle(element).justifyContent), 'center');
  assert.equal(await page.locator('#download').count(), 0);
  assert.equal(await page.locator('.class-list').count(), 0);
  assert.equal(await page.locator('.eyebrow').count(), 0);
  await page.screenshot({path: 'tests/desktop.png', fullPage: true});
  await page.locator('[data-sample="healthy"]').click();
  await page.locator('#preview').waitFor({state: 'visible'});
  assert.equal(await page.locator('.file-info').evaluate(element => getComputedStyle(element).justifyContent), 'space-between');
  await page.locator('#analyze').click();
  await page.locator('#result').waitFor({state: 'visible', timeout: 60000});
  assert.equal(await page.locator('.score').count(), 6);
  assert.ok((await page.locator('.score > span:first-child').allTextContents()).includes('Rice Hispa'));
  await page.getByText('All class scores', {exact: true}).click();
  await page.screenshot({path: 'tests/result.png', fullPage: true});
  await page.locator('#clear').click();
  assert.equal(await page.locator('#analyze').isDisabled(), true);
  assert.equal(await page.locator('.file-info').evaluate(element => getComputedStyle(element).justifyContent), 'center');
  await page.setViewportSize({width: 390, height: 844});
  assert.equal(await page.locator('.page-intro h1').evaluate(element => getComputedStyle(element).textAlign), 'center');
  assert.equal(await page.locator('.page-intro > p').evaluate(element => getComputedStyle(element).textAlign), 'justify');
  assert.equal(await page.locator('.page-intro > p').evaluate(element => Math.round(element.getBoundingClientRect().width) === Math.round(element.parentElement.getBoundingClientRect().width)), true);
  assert.equal(await page.locator('.results-panel').evaluate(element => getComputedStyle(element).borderTopWidth), '1px');
  assert.equal(await page.locator('.image-panel').evaluate(element => getComputedStyle(element).paddingBottom), '20px');
  assert.equal(await page.locator('.analyze').evaluate(element => getComputedStyle(element).justifyContent), 'center');
  assert.equal(await page.locator('.model-note').evaluate(element => getComputedStyle(element).textAlign), 'center');
  await page.screenshot({path: 'tests/mobile.png', fullPage: true});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  await page.getByRole('link', {name: 'About', exact: true}).click();
  await page.locator('.class-row').first().waitFor({state: 'visible'});
  assert.equal(await page.locator('.class-row').count(), 6);
  assert.ok(page.url().endsWith('/about'));
  assert.equal(await page.title(), 'About - PaddyLab');
  assert.equal(await page.getByRole('link', {name: 'Back to Home', exact: true}).count(), 1);
  assert.equal(await page.locator('.back-link').evaluate(element => getComputedStyle(element).backgroundColor), 'rgb(32, 41, 31)');
  assert.equal(await page.locator('.back-link').evaluate(element => getComputedStyle(element).color), 'rgb(255, 255, 255)');
  assert.equal(await page.getByRole('link', {name: 'Analyze', exact: true}).count(), 0);
  assert.equal(await page.locator('.back-label-short').isVisible(), true);
  assert.equal(await page.locator('.back-label-full').isVisible(), false);
  assert.equal(await page.locator('.sample-link').count(), 0);
  assert.equal(await page.locator('.about-detail').count(), 2);
  assert.equal(await page.locator('.about-developer a').innerText(), 'John Carlo Nas');
  assert.equal(await page.locator('.about-intro h1').evaluate(element => getComputedStyle(element).textAlign), 'center');
  assert.equal(await page.locator('.about-developer').evaluate(element => getComputedStyle(element).textAlign), 'center');
  assert.equal(await page.locator('.about-intro > p').first().innerText(), 'Developer: John Carlo Nas');
  assert.equal(await page.locator('.about-description').innerText(), 'PaddyLab is my first AI model, developed as my final project for the Introduction to Artificial Intelligence course. It explores rice leaf conditions by analyzing photos and suggesting a likely class with a confidence score for further inspection.');
  assert.equal(await page.locator('.about-description').evaluate(element => getComputedStyle(element).textAlign), 'justify');
  assert.equal(await page.locator('.about-detail p').first().evaluate(element => getComputedStyle(element).textAlign), 'justify');
  assert.equal(await page.locator('.class-copy p').first().evaluate(element => getComputedStyle(element).textAlign), 'justify');
  assert.equal(await page.locator('.about-detail h2').nth(1).innerText(), 'What the result means?');
  assert.equal(await page.locator('.classes-heading h2').innerText(), 'The Six Classes');
  assert.deepEqual(await page.locator('.class-copy h2').allTextContents(), ['Bacterial Leaf Blight', 'Brown Spot', 'Healthy', 'Leaf Blast', 'Leaf Scald', 'Rice Hispa']);
  assert.ok(await page.locator('.classes-heading h2').evaluate((element) => parseFloat(getComputedStyle(element).fontSize)) > await page.locator('.class-copy h2').first().evaluate((element) => parseFloat(getComputedStyle(element).fontSize)));
  assert.equal(await page.locator('.classes-heading p').count(), 0);
  assert.equal(await page.locator('.site-footer').innerText(), '© 2026 PaddyLab. All rights reserved.');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  await page.emulateMedia({reducedMotion: 'reduce'});
  await page.goto('http://127.0.0.1:5000/?sample=bacterial_leaf_blight');
  await page.locator('#preview').waitFor({state: 'visible'});
  assert.ok((await page.locator('#filename').textContent()).includes('bacterial_leaf_blight'));
  await page.waitForTimeout(100);
  assert.equal(await page.locator('html.motion-ready').count(), 0);
  assert.deepEqual(errors, []);
  console.log('Browser checks passed: inference, scores, reset, mobile width, About page, class grid, sample loading, reduced motion.');
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
